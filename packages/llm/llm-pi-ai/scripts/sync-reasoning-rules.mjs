// Regenerate src/option-map/reasoning-rules.ts from the reference product's built-in provider configuration:
//   node packages/llm/llm-pi-ai/scripts/sync-reasoning-rules.mjs <tp-cowork>/config/provider/tpcowork-builtin.json
import { readFile, writeFile } from 'node:fs/promises'

const [source] = process.argv.slice(2)
if (source === undefined) throw new Error('usage: sync-reasoning-rules.mjs <tpcowork-builtin.json>')
const { config } = JSON.parse(await readFile(source, 'utf8'))
// Template and built-in provider rules name the reference product's own providers, which never match a route here.
const rules = [['model', 'modelRules'], ['model-api', 'modelApiRules'], ['provider-site', 'providerSiteRules']]
  .flatMap(([type, key]) => config.modelConfigRules[key].flatMap(({ config: rule, ...match }) =>
    rule.optionSpecs !== undefined && 'reasoningLevel' in rule.optionSpecs
      ? [{ type, ...match, reasoningLevel: rule.optionSpecs.reasoningLevel }]
      : []))
const output = `// Generated by scripts/sync-reasoning-rules.mjs from the reference product's built-in provider rules; do not edit.
import type { ReasoningRule } from '../reasoning-rules.ts'

/** The reference product's reasoning-level rules, in its application order. */
export const REASONING_RULES: readonly ReasoningRule[] = ${JSON.stringify(rules, null, 2)}
`
await writeFile(new URL('../src/option-map/reasoning-rules.ts', import.meta.url), output)
console.log(`wrote ${rules.length} reasoning rules`)
